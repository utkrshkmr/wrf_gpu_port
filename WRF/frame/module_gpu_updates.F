!WRF:DRIVER_LAYER:UTIL
!
! module_gpu_updates: moves the state of one domain between its host copy and
! its device copy (plan.md P1.3; port/agent/PHASE1.md P1.3).
!
! The lists of fields are generated by the Registry (WRF/tools/gen_gpu.c):
!
!   inc/gpu_upd_dev_all.inc    host -> device update of every allocated field
!   inc/gpu_upd_host_all.inc   device -> host update of every allocated field
!   inc/gpu_upd_dev_bdy.inc    host -> device update of the boundary arrays
!
! Each line calls a by-address routine of module_gpu_map, e.g.
!   CALL gpu_map_r(grid%u_2, SIZE(grid%u_2,KIND=8), GPU_UPD_TO)
!
! A field is moved when in_use_for_config says it is allocated at full size
! (the same test allocs.inc uses); boundary arrays are always moved.  The
! fields are mapped when they are allocated (P1.2), so these routines only
! copy.  Intermediate grids of nest forcing stay on the host (P1.2) and are
! never moved.  Without WRF_GPU every routine is empty.
!
! gpu_upd_host_stream copies what an output stream writes.  Through Phase 4 it
! copies the whole state (correct, only slower than a per-stream walk of
! grid%head_statevars); P5.3 revisits it when the device copy becomes the
! current one (PHASE5.md).

MODULE module_gpu_updates

   USE module_domain, ONLY : domain
   USE module_configure, ONLY : in_use_for_config
   USE module_gpu_map

   IMPLICIT NONE
   PRIVATE

   PUBLIC :: gpu_upd_dev_all, gpu_upd_host_all, gpu_upd_dev_bdy, gpu_upd_host_stream

CONTAINS

   SUBROUTINE gpu_upd_dev_all ( grid )
      ! host -> device: every allocated field of grid
      TYPE(domain), INTENT(INOUT) :: grid
#ifdef WRF_GPU
      IF ( grid%is_intermediate ) RETURN
#  include "gpu_upd_dev_all.inc"
#endif
   END SUBROUTINE gpu_upd_dev_all

   SUBROUTINE gpu_upd_host_all ( grid )
      ! device -> host: every allocated field of grid
      TYPE(domain), INTENT(INOUT) :: grid
#ifdef WRF_GPU
      IF ( grid%is_intermediate ) RETURN
#  include "gpu_upd_host_all.inc"
#endif
   END SUBROUTINE gpu_upd_host_all

   SUBROUTINE gpu_upd_dev_bdy ( grid )
      ! host -> device: the lateral boundary arrays of grid (_bxs ... _btye)
      TYPE(domain), INTENT(INOUT) :: grid
#ifdef WRF_GPU
      IF ( grid%is_intermediate ) RETURN
#  include "gpu_upd_dev_bdy.inc"
#endif
   END SUBROUTINE gpu_upd_dev_bdy

   SUBROUTINE gpu_upd_host_stream ( grid , stream )
      ! device -> host before output of stream (sync points S3, S4).
      ! Phases 1-4: the whole state.
      TYPE(domain), INTENT(INOUT) :: grid
      INTEGER,      INTENT(IN)    :: stream
#ifdef WRF_GPU
      CALL gpu_upd_host_all ( grid )
#endif
   END SUBROUTINE gpu_upd_host_stream

END MODULE module_gpu_updates
